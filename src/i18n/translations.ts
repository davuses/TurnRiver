export const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  en,
  'zh-CN': zhCN,
};

export function translateKey(locale: Locale, key: TranslationKey): string {
  return TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key];
}

export function translateGrade(locale: Locale, grade: DecisionGrade): string {
  return translateKey(locale, `grade.${grade}` as TranslationKey);
}

export function translateModuleLabel(locale: Locale, mod: DrillModule): string {
  return translateKey(locale, `nav.${mod}` as TranslationKey);
}

/**
 * Position filters, table seats, and range matrices retain standard poker codes
 * (UTG, HJ, CO, BTN, SB, BB) without literal Chinese translations like 劫持/关煞.
 */
export function translatePositionLabel(locale: Locale, pos: Position | 'ALL'): string {
  if (pos === 'ALL') return locale === 'zh-CN' ? '全部位置' : 'All Seats';
  return pos;
}

export function translateStreetLabel(locale: Locale, street: Street | 'SHOWDOWN' | string): string {
  const lower = street.toLowerCase();
  if (lower === 'preflop') return translateKey(locale, 'street.preflop');
  if (lower === 'flop') return translateKey(locale, 'street.flop');
  if (lower === 'turn') return translateKey(locale, 'street.turn');
  if (lower === 'river') return translateKey(locale, 'street.river');
  if (lower === 'showdown') return translateKey(locale, 'street.showdown');
  return street;
}

export function translateActionText(locale: Locale, text: string): string {
  if (locale === 'en') return text;
  return text
    .replace(/\bCalls?\s+All-In\s*\(([\d.]+bb)\)/gi, '跟注全下（$1）')
    .replace(/\bGoes\s+All-In\s+to\s+([\d.]+bb)\b/gi, '全下到 $1')
    .replace(/\bPosts\s+SB\s+([\d.]+bb)\b/gi, '下小盲 $1')
    .replace(/\bPosts\s+BB\s+([\d.]+bb)\b/gi, '下大盲 $1')
    .replace(/\bPosts\s+SB\b/gi, '下小盲')
    .replace(/\bPosts\s+BB\b/gi, '下大盲')
    .replace(/\bBlind\s+([\d.]+bb)\b/gi, '盲注 $1')
    .replace(/\bCheck-Raises?\s+to\s+([\d.]+bb)\b/gi, '过牌加注到 $1')
    .replace(/\bCheck-Raises?\b/gi, '过牌加注')
    .replace(/\bOverbets?\b/gi, '超池下注')
    .replace(/\b3-Bets?(?:\s+to)?\s+([\d.]+bb)\b/gi, '3-Bet 到 $1')
    .replace(/\b4-Bets?(?:\s+to)?\s+([\d.]+bb)\b/gi, '4-Bet 到 $1')
    .replace(/\b3-Bets\b/gi, '3-Bet')
    .replace(/\b4-Bets\b/gi, '4-Bet')
    .replace(/\bRaise\s+All-In\b/gi, '加注全下')
    .replace(/\bShoves?\b/gi, '全下')
    .replace(/\bFolded\b/gi, '已弃牌')
    .replace(/\bFolds?\b/gi, '弃牌')
    .replace(/\bChecks?\b/gi, '过牌')
    .replace(/\bCalls?\b/gi, '跟注')
    .replace(/\bRaises?\s+to\b/gi, '加注到')
    .replace(/\bRaises?\b/gi, '加注')
    .replace(/\bOpens?\b/gi, '开池加注')
    .replace(/(?<!-)\bBets?\b/gi, '下注')
    .replace(/\bAll-In\b/gi, '全下')
    .replace(/\bAction on\b/gi, '轮到')
    .replace(/\bFlop\b/g, '翻牌')
    .replace(/\bTurn\b/g, '转牌')
    .replace(/\bRiver\b/g, '河牌')
    .replace(/\bPot\b/gi, '底池')
    .replace(/\bsolver combos\b/gi, '个参考组合')
    .replace(/\bcombos\b/gi, '个组合')
    .replace(/\boverlap\b/gi, '重合度');
}

